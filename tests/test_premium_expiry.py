TOWNS = {t.name: t for t in read_towns(SERVER_DIR / "data" / "world" / "Tibia74.otbm")}
THAIS, EDRON, CARLIN, ROOKGAARD = (TOWNS[n] for n in ("Thais", "Edron", "Carlin", "Rookgaard"))
