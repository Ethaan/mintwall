# ---------------------------------------------------------------------------------------------- the house

HOUSE_NAME, HOUSE_TILE = "Castle Shop 2", (33208, 31798, 7)    # house 474, Edron (Tibia74-houses.xml, townid 6)


def _house_of(gm, name):
    start = len(gm.text_messages)
    gm.say(f"/gethouse {name}")
    assert gm.wait_for(lambda: any(name in t and "house" in t for _, t in gm.text_messages[start:]), timeout=3)
    return next(t for _, t in gm.text_messages[start:] if name in t and "house" in t)


@pytest.mark.parametrize("premium_days", [0, 30], ids=["free", "premium"])
def test_the_house_is_kept_at_login(new_player, db, server, items, premium_days):
    """Tibiantis FAQ: "Houses are lost during the next server save" - not at the login. The release (items to the
    depot of the house's town) is test_server_save.py's."""
    owner = db.create_character(pos=THAIS_ROAD, premium_days=premium_days, town_id=THAIS.id, storage=BEGINNER_SET)
    gm = new_player(pos=HOUSE_TILE, group_id=3, storage=BEGINNER_SET)
    gm.say(f"/owner {owner.name}")
    assert gm.wait_for(lambda: HOUSE_NAME in _house_of(gm, owner.name), timeout=5)
    p = _login_as(server, items, owner)
    try:
        time.sleep(1)
        assert not p.messages("lost your house")
        assert HOUSE_NAME in _house_of(gm, owner.name)
    finally:
        p.logout()
    # free the house again for the other tests of the session (/owner kicked the first GM out of it)
    gm2 = new_player(pos=HOUSE_TILE, group_id=3, storage=BEGINNER_SET)
    gm2.say("/owner none")
    assert gm2.wait_for(lambda: "does not own any house" in _house_of(gm2, owner.name), timeout=5)


# ---------------------------------------------------------------------------------------------- the outfit

NOBLEMAN, SUMMONER, HUNTER = 132, 133, 129     # male: 128-131 free, 132-134 premium (protocolgame.cpp)


def _with_outfit(new_player, db, server, items, looktype, premium_days=0):
    """A character that logs in wearing `looktype` (the one it chose while it had premium)."""
    p = new_player(pos=THAIS_ROAD, premium_days=30, storage=BEGINNER_SET)
    character = p.character
    p.logout()
    con = db._connect()
    con.execute("UPDATE players SET looktype = ?, lookhead = 1, lookbody = 2, looklegs = 3, lookfeet = 4 WHERE id = ?",
                (looktype, character.guid))
    con.execute("UPDATE accounts SET premend = ? WHERE id = ?",
                (int(time.time()) + premium_days * 86400 if premium_days else 0, character.account))
    con.commit()
    con.close()
    time.sleep(1)
    return _login_as(server, items, character)


def _outfit(c):
    return c.wait_for(lambda: c.creatures.get(c.player_id), timeout=5).outfit


def _set_outfit(c, looktype, colours=(10, 20, 30, 40)):
    c._send(Writer().u8(0xD3).u8(looktype).u8(colours[0]).u8(colours[1]).u8(colours[2]).u8(colours[3]))
    time.sleep(1)


def test_the_premium_outfit_is_kept_at_login(new_player, db, server, items):
    p = _with_outfit(new_player, db, server, items, NOBLEMAN)
    try:
        assert _outfit(p) == (NOBLEMAN, 1, 2, 3, 4)
    finally:
        p.logout()


def test_the_kept_premium_outfit_can_get_new_colours(new_player, db, server, items):
    """Needs the protocolgame.cpp change (rebuild): the old server turned the character invisible (look type 0)."""
    p = _with_outfit(new_player, db, server, items, NOBLEMAN)
