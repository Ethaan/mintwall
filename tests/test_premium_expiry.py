    p = new_player(pos=where, premium_days=0, town_id=CARLIN.id, storage=BEGINNER_SET)
    assert p.wait_for(lambda: p.pos == THAIS.temple, timeout=5), f"logged in at {p.pos}, not the Thais temple"
    assert p.wait_for(lambda: p.messages(MOVED), timeout=3), p.text_messages[-3:]


