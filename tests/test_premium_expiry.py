THAIS_ROAD = (32369, 32245, 7)              # just south of the Thais temple
MOVED = "You have been moved out of the premium area."
BEGINNER_SET = {30001: 1}


def _login_as(server, items, character):
    c = GameClient(items, port=server.port)
    c.login(character.account, character.password, character.name)
    c.character = character
    return c


# ---------------------------------------------------------------------------------------------- premium areas

def test_premium_areas_match_the_map(world_map):
    """premium_areas.lua is what the map says: every tile you can only reach through a premium ship, carpet or King's
    Bridge is in a box, no tile you can walk to from a free town is (rerun tools/premium-areas.py after a map change)."""
    from tibia74.premium import areas, read_lua_boxes
    boxes = read_lua_boxes(SERVER_DIR / "data" / "creaturescripts" / "lib" / "premium_areas.lua")
    assert boxes, "premium_areas.lua has no boxes"

    def area_of(p):
        return next((name for lo, hi, name in boxes if all(lo[i] <= p[i] <= hi[i] for i in range(3))), None)

    free, premium = areas(world_map, SERVER_DIR)
    wrong_free = [p for p in free if area_of(p)]
    assert not wrong_free, f"{len(wrong_free)} free tiles inside a premium box, e.g. {wrong_free[:5]}"
    for name, tiles in premium.items():
        missing = [p for p in tiles if area_of(p) != name]
        assert not missing, f"{len(missing)} {name} premium tiles outside its boxes, e.g. {missing[:5]}"
    for town in ("Edron", "Darashia", "Ankrahmun"):
        assert area_of(TOWNS[town].temple) == "mainland", town
    for town in ("Thais", "Carlin", "Kazordoon", "Ab'Dendriel", "Venore", "Fibula", "Rookgaard"):
        assert area_of(TOWNS[town].temple) is None, town
    assert area_of(ROOK_PREMIUM_SIDE) == "rookgaard"


